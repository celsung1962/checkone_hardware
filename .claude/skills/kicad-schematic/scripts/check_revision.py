#!/usr/bin/env python3
"""check_revision.py - every title block of a KiCad project carries the same revision and date (SKILL.md "Revisions").

When a new revision of the board starts (rev. 0.1 -> 0.2, A -> B), its number and date go into the title block of
every schematic sheet and of the board, at the start of that revision, not at the release. A sheet left at the old
number is printed, reviewed and archived as the wrong revision (ServiceOne rev. 0.2, 2026-10-21: every sheet still
read 0.1 after the first rev. 0.2 changes).

    check_revision.py <project dir> [--rev 0.2] [--date 2026-10-21]

Reads the (title_block ...) of every *.kicad_sch (backups, autosave files and -bak / _old copies skipped) and of
every *.kicad_pcb in the folder. FAIL (exit 1): a title block without a revision, two different revisions or two
different dates, or a revision / date other than --rev / --date when given. A schematic generated by a script gets
the revision from the generator's constant: change it there, not in KiCad.
"""
import glob
import os
import re
import sys

SKIP = re.compile(r'(^_autosave-|-bak|_old|\.bak|backups)', re.I)


def title_block(path):
    t = open(path, encoding='utf-8', errors='replace').read()
    m = re.search(r'\(title_block(.*?)\)\s*\((?:lib_symbols|paper|general|layers|setup|comment)', t, re.S)
    blk = m.group(1) if m else (re.search(r'\(title_block(.{0,2000})', t, re.S) or [None, ''])[1]
    rev = re.search(r'\(rev\s+"([^"]*)"\)', blk)
    date = re.search(r'\(date\s+"([^"]*)"\)', blk)
    return (rev.group(1) if rev else None), (date.group(1) if date else None)


def main():
    a = sys.argv[1:]
    if not a or a[0].startswith('-'):
        print(__doc__)
        return 2
    d = a[0]
    want_rev = a[a.index('--rev') + 1] if '--rev' in a else None
    want_date = a[a.index('--date') + 1] if '--date' in a else None
    files = [f for f in sorted(glob.glob(os.path.join(d, '*.kicad_sch')) + glob.glob(os.path.join(d, '*.kicad_pcb')))
             if not SKIP.search(os.path.basename(f))]
    if not files:
        print('FAIL no .kicad_sch / .kicad_pcb in %s' % d)
        return 1
    rows = [(os.path.basename(f),) + title_block(f) for f in files]
    fails = 0
    for name, rev, date in rows:
        print('  %-36s rev %-8s date %s' % (name, rev, date))
        if not rev:
            fails += 1
            print('FAIL %s: no revision in the title block' % name)
    revs = {r for _, r, _ in rows if r}
    dates = {x for _, _, x in rows if x}
    if len(revs) > 1:
        fails += 1
        print('FAIL different revisions: %s' % ', '.join(sorted(revs)))
    if len(dates) > 1:
        fails += 1
        print('FAIL different dates: %s' % ', '.join(sorted(dates)))
    if want_rev and revs != {want_rev}:
        fails += 1
        print('FAIL revision is %s, expected %s' % (', '.join(sorted(revs)) or '-', want_rev))
    if want_date and dates != {want_date}:
        fails += 1
        print('FAIL date is %s, expected %s' % (', '.join(sorted(dates)) or '-', want_date))
    print('title blocks: %d file(s), revision %s, %s' % (len(rows), '/'.join(sorted(revs)) or '-',
                                                          'FAIL' if fails else 'PASS'))
    return 1 if fails else 0


if __name__ == '__main__':
    sys.exit(main())
