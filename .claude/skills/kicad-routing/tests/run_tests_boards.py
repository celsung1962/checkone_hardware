#!/usr/bin/env python
"""run_tests_boards.py - exercise the 2-layer and 6-layer branches of the rulebook.

Every fixture in run_tests.js is 4-layer, so until rev K the 2L and 6L branches of the stackup
rules had never been run by any test - they were documented, not verified. This derives 2- and
6-layer boards from the generated 4-layer fixture and checks the audit reaches a sensible verdict
on each.

Runs on the SYSTEM python plus node. No pcbnew required.

    python tests/run_tests_boards.py
"""
import io
import os
import re
import sys
import json
import shutil
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL = os.path.dirname(HERE)
FX = os.path.join(HERE, 'fixtures')
AUDIT = os.path.join(SKILL, 'scripts', 'kicad_audit.js')
OUT = os.path.join(HERE, 'fixtures_boards')

PASS = FAIL = 0


def check(label, cond, detail=''):
    global PASS, FAIL
    if cond:
        PASS += 1
        print('PASS  %s%s' % (label, ('  - ' + str(detail)) if detail else ''))
    else:
        FAIL += 1
        print('FAIL  %s  - %s' % (label, detail))


def node(*a):
    p = subprocess.run(['node'] + list(a), capture_output=True, text=True)
    return p.returncode, p.stdout, p.stderr


# the 4-layer fixture is generated by run_tests.js; build it if it is not there yet
good = os.path.join(FX, 'good.kicad_pcb')
if not os.path.isfile(good):
    subprocess.run(['node', os.path.join(HERE, 'run_tests.js')], capture_output=True, text=True)
if not os.path.isfile(good):
    print('FAIL  cannot generate the 4-layer fixture (run_tests.js)')
    sys.exit(1)

if os.path.isdir(OUT):
    shutil.rmtree(OUT)
os.makedirs(OUT)

src = io.open(good, encoding='utf-8', newline='').read()
pro_src = os.path.join(FX, 'good.kicad_pro')
params_src = os.path.join(FX, 'kicad_golden.project.json')

LAYERS_2 = '\t\t(0 "F.Cu" signal) (2 "B.Cu" signal)\n'
LAYERS_6 = ('\t\t(0 "F.Cu" signal) (4 "In1.Cu" power) (6 "In2.Cu" signal) '
            '(8 "In3.Cu" signal) (10 "In4.Cu" power) (2 "B.Cu" signal)\n')


def variant(name, layer_line, drop_inner_zones):
    """Write a board with a different copper stack. Everything else is the known-good fixture."""
    txt = src
    # replace the copper layer declarations (the line carrying F.Cu ... B.Cu)
    m = re.search(r'^\t\t\(0 "F\.Cu".*$', txt, re.M)
    assert m, 'cannot find the copper layer line in the fixture'
    txt = txt[:m.start()] + layer_line.rstrip('\n') + txt[m.end():]
    if drop_inner_zones:
        # a 2-layer board has no In*.Cu zones; drop them so the board is self-consistent
        txt = re.sub(r'\t\(zone[^\0]*?\(layer "In\d\.Cu"\)[^\0]*?\n\t\)\n', '', txt)
    b = os.path.join(OUT, name + '.kicad_pcb')
    io.open(b, 'w', encoding='utf-8', newline='').write(txt)
    if os.path.isfile(pro_src):
        shutil.copy2(pro_src, os.path.join(OUT, name + '.kicad_pro'))
    if os.path.isfile(params_src) and not os.path.isfile(os.path.join(OUT, 'kicad_golden.project.json')):
        shutil.copy2(params_src, os.path.join(OUT, 'kicad_golden.project.json'))
    return b


def audit(board, tag):
    j = os.path.join(OUT, tag + '.audit.json')
    rc, so, se = node(AUDIT, board, '--json', j, '--no-sch', '--quiet')
    if not os.path.isfile(j):
        return None, (se or so)[:200]
    with io.open(j, encoding='utf-8') as f:
        return json.load(f), ''


# ---------------------------------------------------------------- 4-layer control
rep4, err = audit(good, 'l4')
check('4-layer fixture still audits', rep4 is not None, err)
if rep4:
    check('4-layer: copper layers reported as 4',
          rep4['stats'].get('copper_layers') == ['F.Cu', 'In1.Cu', 'In2.Cu', 'B.Cu'],
          rep4['stats'].get('copper_layers'))

# ---------------------------------------------------------------- 2-layer
b2 = variant('two_layer', LAYERS_2, drop_inner_zones=True)
rep2, err = audit(b2, 'l2')
check('2-layer board audits without crashing', rep2 is not None, err)
if rep2:
    cl = rep2['stats'].get('copper_layers')
    check('2-layer: only F.Cu and B.Cu are seen', cl == ['F.Cu', 'B.Cu'], cl)
    # The rulebook says a 2-layer board has no inner planes. The audit must NOT demand them.
    bad = [f for f in rep2['findings']
           if f['level'] == 'FAIL' and re.search(r'In[12]\.Cu|inner', f['msg'], re.I)]
    check('2-layer: no FAIL demanding inner-layer planes', not bad,
          '; '.join(f['msg'][:70] for f in bad[:3]))

# ---------------------------------------------------------------- 6-layer
b6 = variant('six_layer', LAYERS_6, drop_inner_zones=False)
rep6, err = audit(b6, 'l6')
check('6-layer board audits without crashing', rep6 is not None, err)
if rep6:
    cl = rep6['stats'].get('copper_layers') or []
    check('6-layer: all six copper layers are seen', len(cl) == 6, cl)
    crash = [f for f in rep6['findings'] if f['level'] == 'FAIL' and 'parse' in f['msg'].lower()]
    check('6-layer: no parse failure', not crash, '; '.join(f['msg'][:70] for f in crash[:2]))

print('\n%d/%d assertions passed' % (PASS, PASS + FAIL))
sys.exit(1 if FAIL else 0)
